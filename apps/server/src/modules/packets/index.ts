const PDF_TYPE = 'application/pdf'
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

/** PROPOSED: at most 60 packet PDFs per staff member per hour (no owner value). */
export const PACKET_PDF_RATE = { bucket: 'job-packet-pdf', limit: 60, windowSeconds: 3600 } as const

export type PacketsDeps = {
  storage?: ObjectStorage | null
  /** Whether the access-code store is configured (ACCESS_CODE_ENCRYPTION_KEY set): only then is Reveal offered. */
  accessCodes?: boolean
}

function staff(ctx: ApiContext): StaffActor {
  if (ctx.actor.kind !== 'staff') throw new ApiError('FORBIDDEN')
  return ctx.actor
}
const jobIdOf = (ctx: ApiContext) => (ctx.req.params as { jobId: string }).jobId
const requestIdOf = (ctx: ApiContext) => currentContext()?.requestId ?? ctx.req.id
const localeOf = (ctx: ApiContext): StaffLocale => resolveStaffLocale(ctx.req.apiActor?.locale)

/** The record facts: the job's project and its assignments (the policy's A cell decides on them). */
const jobFacts: NonNullable<RouteDef['resource']> = async ({ req, db }) => {
  const { jobId } = req.params as { jobId: string }
  if (!UUID_RE.test(jobId)) return null
  const job = await db.selectFrom('work.jobs').select('project_id').where('id', '=', jobId).executeTakeFirst()
  return job ? { projectId: job.project_id, assignments: await jobAssignments(db, jobId) } : null
}

/** The job inside the caller's scope (else NOT_FOUND, an altered ID finds nothing), brought up to date. */
async function currentPacket(ctx: ApiContext, db: Db | Tx = ctx.db): Promise<PacketRow> {
  const jobId = jobIdOf(ctx)
  const job = await db
    .selectFrom('work.jobs as j')
    .select('j.id')
    .where('j.id', '=', jobId)
    .where(jobInScope('j.id', ctx.scope))
    .executeTakeFirst()
  if (!job) throw new ApiError('NOT_FOUND')
  const row = await refreshJobPacket(db, jobId)
  if (!row) throw new ApiError('NOT_FOUND')
  return row
}

async function firstGeneratedAt(db: Db | Tx, jobId: string): Promise<Date> {
  const r = await db
    .selectFrom('work.job_packets')
    .select('generated_at')
    .where('job_id', '=', jobId)
    .where('version', '=', 1)
    .executeTakeFirstOrThrow()
  return r.generated_at
}

const versionField = () =>
  new ApiError('VALIDATION_FAILED', { fieldErrors: [{ field: 'body.version', code: 'unknown_version', message: '' }] })

export function packetsModule(deps: PacketsDeps = {}): ApiModule {
  const storage = deps.storage ?? null
  const accessCodes = deps.accessCodes ?? false
  const common = {
    actors: ['staff'] as const,
    permission: 'job.view_packet' as const,
    rateLimit: 'none' as const,
    pagination: false,
    test: TEST,
    resource: jobFacts,
  }

  const view: RouteDef = {
    ...common,
    method: 'GET',
    path: '/staff/jobs/:jobId/packet',
    operationId: 'getJobPacket',
    summary: 'The current job packet',
    description:
      'Staff with job.view_packet inside their scope: the Owner and Office; the Estimator (PROPOSED cell); a worker ' +
      'only while assigned to a live visit of the job (an active confirmed reservation, until the end of the service ' +
      'day; a removed worker is refused on the next request). The server first brings the packet up to date (a new ' +
      'version when its records changed). Answers the version, its first-generated, last-updated and checked times, ' +
      'whether it is the latest, "What changed since you reviewed this?" against the version the caller last viewed, ' +
      'and every section of HH-PKT-01 from stored records only (no price, never an access code: a code is revealed ' +
      'separately, online, on the visit date). What no record holds is marked, never filled in. Also where the ' +
      "caller's own acknowledgment stands (acknowledged, required, invalidated by a critical change, a removed " +
      'assignment or a disabled account, or not assigned) with what changed since the acknowledged version, and ' +
      "each assigned worker's state. Nobody inherits another person's acknowledgment.",
    kind: 'read',
    idempotency: 'none',
    expectedVersion: 'none',
    audit: 'none',
    schema: { params: JOB_PARAMS, response: { 200: PACKET_VIEW_WITH_ACTIONS } },
    handler: async (ctx) => {
      const actor = staff(ctx)
      const row = await currentPacket(ctx)
      const now = new Date()
      const body = await packetView(ctx.db, {
        row,
        latestVersion: row.version,
        firstGeneratedAt: await firstGeneratedAt(ctx.db, row.jobId),
        viewed: await lastViewed(ctx.db, row.jobId, actor.userId),
        storage,
        now,
      })
      // Whether the Reveal button is offered: the server decides again, with the same facts, when it is pressed.
      const zone = (await loadConfig(ctx.db)).get('business.timezone')
      const today = zone.state === 'CONFIGURED' ? localDate(now, zone.value.zone) : undefined
      const facts = await propertyVisitFacts(ctx.db, row.content.site_access.propertyId, actor)
      const revealAccessCodes =
        accessCodes &&
        decide(actor, 'access_code.reveal', facts, { now, online: true, ...(today ? { today } : {}) }).effect ===
          'allow'
      const assigned = (await assignedNow(ctx.db, row.jobId, now)).includes(actor.userId)
      const mine = await acknowledgmentStatus(ctx.db, row, actor.userId, assigned)
      const team = await teamAcknowledgments(ctx.db, row, now)
      return {
        body: {
          ...body,
          acknowledgments: { mine, team },
          actions: { revealAccessCodes, acknowledge: assigned && mine.state !== 'acknowledged' },
        },
        headers: { 'cache-control': 'no-store' },
      }
    },
  }

  const versions: RouteDef = {
    ...common,
    method: 'GET',
    path: '/staff/jobs/:jobId/packet/versions',
    operationId: 'listJobPacketVersions',
    summary: 'The versions of a job packet',
    description:
      'Staff with job.view_packet inside their scope (as for the packet). Every version, newest first, with when it ' +
      'was generated, what changed against the version before it and whether a change was critical (scope, holds, ' +
      'SOP version, assignment, site access). Versions are never changed or deleted.',
    kind: 'read',
    idempotency: 'none',
    expectedVersion: 'none',
    audit: 'none',
    schema: { params: JOB_PARAMS, response: { 200: VERSIONS_VIEW } },
    handler: async (ctx) => {
      const row = await currentPacket(ctx)
      const rows = await ctx.db
        .selectFrom('work.job_packets')
        .select(['version', 'generated_at', 'critical', 'changes'])
        .where('job_id', '=', row.jobId)
        .orderBy('version', 'desc')
        .execute()
      return {
        body: {
          versions: rows.map((r) => ({
            version: r.version,
            generatedAt: r.generated_at,
            critical: r.critical,
            changes: r.changes,
          })),
        },
      }
    },
  }

  const recordView: RouteDef = {
    ...common,
    method: 'POST',
    path: '/staff/jobs/:jobId/packet/views',
    operationId: 'recordJobPacketView',
    summary: 'Record that the caller viewed a packet version',
    description:
      'Staff with job.view_packet inside their scope (as for the packet). Records that the caller viewed the given ' +
      'version (a version the job has), so the packet later shows what changed since then. Personal: it records the ' +
      'caller only. A view is not an acknowledgment: it releases nothing and passes no gate. Audited.',
    kind: 'write',
    idempotency: 'none',
    expectedVersion: 'none',
    audit: 'job_packet.view',
    schema: { params: JOB_PARAMS, body: VERSION_BODY, response: { 200: VIEW_RECORDED } },
    handler: async (ctx) => {
      const tx = ctx.tx as Tx
      const actor = staff(ctx)
      const latest = await currentPacket(ctx, tx)
      const { version } = ctx.req.body as { version: number }
      const row = version === latest.version ? latest : await packetVersion(tx, latest.jobId, version)
      if (!row) throw versionField()
      const viewed = await tx
        .insertInto('work.job_packet_views')
        .values({ packet_id: row.id, job_id: row.jobId, version: row.version, staff_user_id: actor.userId })
        .returning('viewed_at')
        .executeTakeFirstOrThrow()
      await ctx.audit({
        target: { type: 'job_packet', id: row.jobId, version: row.version },
        summary: { version: row.version, latestVersion: latest.version },
      })
      return { body: { version: row.version, viewedAt: viewed.viewed_at } }
    },
  }

  /** Records one export (who, when, which version, the latest then) and audits it, in the given transaction. */
  async function recordExport(tx: Tx, ctx: ApiContext, row: PacketRow, latestVersion: number, format: 'print' | 'pdf') {
    const actor = staff(ctx)
    const out = await tx
      .insertInto('work.job_packet_exports')
      .values({
        packet_id: row.id,
        job_id: row.jobId,
        version: row.version,
        latest_version: latestVersion,
        staff_user_id: actor.userId,
        format,
        request_id: requestIdOf(ctx).slice(0, 200),
      })
      .returning(['id', 'exported_at'])
      .executeTakeFirstOrThrow()
    const event = {
      target: { type: 'job_packet', id: row.jobId, version: row.version },
      summary: { format, version: row.version, latestVersion, current: row.version === latestVersion },
    }
    // A write route records through its own audit (counted by the framework); the PDF read records it here.
    if (ctx.tx) await ctx.audit(event)
    else
      await audit.record(tx, {
        ...event,
        actor: { kind: 'staff', id: actor.userId, roles: actor.roles },
        action: 'job_packet.export',
        requestId: requestIdOf(ctx),
      })
    return {
      exportId: out.id,
      version: row.version,
      latestVersion,
      current: row.version === latestVersion,
      format,
      exportedAt: out.exported_at,
    }
  }

  const print: RouteDef = {
    ...common,
    method: 'POST',
    path: '/staff/jobs/:jobId/packet/exports',
    operationId: 'recordJobPacketPrint',
    summary: 'Record a print of a packet version',
    description:
      'Staff with job.view_packet inside their scope (as for the packet; PROPOSED: printing uses the view permission). ' +
      'Records and audits the print of the given version (who, when, which version, the latest version then); the ' +
      'staff app then prints its print view, which carries the version and "Printed <time>; check the app for ' +
      'changes" and never an access code. An older version is recorded as stale.',
    kind: 'write',
    idempotency: 'none',
    expectedVersion: 'none',
    audit: 'job_packet.export',
    schema: { params: JOB_PARAMS, body: PRINT_BODY, response: { 201: EXPORT_RECORDED } },
    handler: async (ctx) => {
      const tx = ctx.tx as Tx
      const latest = await currentPacket(ctx, tx)
      const { version } = ctx.req.body as { version: number }
      const row = version === latest.version ? latest : await packetVersion(tx, latest.jobId, version)
      if (!row) throw versionField()
      return { status: 201, body: await recordExport(tx, ctx, row, latest.version, 'print') }
    },
  }

  const pdf: RouteDef = {
    ...common,
    method: 'GET',
    path: '/staff/jobs/:jobId/packet/pdf',
    operationId: 'getJobPacketPdf',
    summary: 'The printable PDF of a packet version',
    description:
      'Staff with job.view_packet inside their scope (as for the packet). The PDF of the given version (default: the ' +
      'latest), in the caller\'s interface language: every page says "Printed <time>; check the app for changes" ' +
      'with the version, an older version says it is not the latest, and it never contains an access code, a code ' +
      'label, a price or a photo link. Each download is recorded and audited as an export (who, when, which version). ' +
      'Never cached. PROPOSED limit: 60 per staff member per hour.',
    kind: 'read',
    idempotency: 'none',
    expectedVersion: 'none',
    audit: 'none',
    rateLimit: PACKET_PDF_RATE,
    binaryResponse: { contentTypes: [PDF_TYPE] },
    schema: { params: JOB_PARAMS, querystring: PDF_QUERY, response: { 200: FILE } },
    handler: async (ctx) => {
      const actor = staff(ctx)
      const latest = await currentPacket(ctx)
      const asked = (ctx.req.query as { version?: number }).version
      const row =
        asked === undefined || asked === latest.version ? latest : await packetVersion(ctx.db, latest.jobId, asked)
      if (!row) throw new ApiError('NOT_FOUND')
      const now = new Date()
      const viewBody = await packetView(ctx.db, {
        row,
        latestVersion: latest.version,
        firstGeneratedAt: await firstGeneratedAt(ctx.db, row.jobId),
        viewed: await lastViewed(ctx.db, row.jobId, actor.userId),
        storage: null,
        now,
      })
      const bytes = await renderPacketPdf({
        view: viewBody,
        locale: localeOf(ctx),
        printedAt: now,
        timeZone: row.content.site_access.timeZone,
      })
      // Recorded and audited before the bytes leave: an export that cannot be recorded is not served.
      await withTx(ctx.db, (tx) => recordExport(tx, ctx, row, latest.version, 'pdf'))
      return {
        body: bytes,
        headers: {
          'content-type': PDF_TYPE,
          'content-disposition': `attachment; filename="job-packet-${row.content.identity.projectReference}-v${row.version}.pdf"`,
          'cache-control': 'no-store',
        },
      }
    },
  }

  const mine: RouteDef = {
    method: 'GET',
    path: '/staff/my/job-packets',
    operationId: 'listMyJobPackets',
    summary: "The caller's assigned jobs and their packets",
    description:
      "Staff with schedule.view_my_day: only the caller's own assignments (active confirmed reservations on live " +
      "work visits whose service day has not ended), grouped by job, with the packet's current version (brought up " +
      'to date first), the version the caller last viewed and whether it changed since then, critically or not, and ' +
      "where the caller's own acknowledgment stands. Nothing about another person's assignments.",
    actors: ['staff'],
    permission: 'schedule.view_my_day',
    kind: 'read',
    idempotency: 'none',
    expectedVersion: 'none',
    rateLimit: 'none',
    audit: 'none',
    pagination: false,
    test: TEST,
    schema: { response: { 200: MY_PACKETS } },
    handler: async (ctx) => {
      const actor = staff(ctx)
      const rows = await ctx.db
        .selectFrom('work.reservations as r')
        .innerJoin('work.visits as v', 'v.id', 'r.visit_id')
        .innerJoin('crm.projects as p', 'p.id', 'v.project_id')
        .select([
          'v.job_id',
          'p.reference',
          'v.id',
          'v.number',
          'v.purpose',
          'v.state',
          'v.local_date',
          'v.window_start',
          'v.window_end',
          'v.time_zone',
          'r.role',
        ])
        .where('r.staff_user_id', '=', actor.userId)
        .where('r.resource', '=', 'worker')
        .where('r.kind', '=', 'confirmed')
        .where('r.ended_at', 'is', null)
        .where('v.job_id', 'is not', null)
        .where('v.state', 'in', [...PACKET_VISIT_STATES])
        .where(sql<boolean>`now() < ((v.local_date + 1)::timestamp AT TIME ZONE v.time_zone)`)
        .orderBy('v.starts_at')
        .orderBy('v.number')
        .execute()
      const jobs = [...new Set(rows.map((r) => r.job_id as string))]
      const now = new Date()
      const assigned: string[] = []
      for (const jobId of jobs) if ((await assignedNow(ctx.db, jobId, now)).includes(actor.userId)) assigned.push(jobId)
      const packets = []
      for (const jobId of jobs) {
        const row = await refreshJobPacket(ctx.db, jobId)
        if (!row) continue
        const seen = await lastViewed(ctx.db, jobId, actor.userId)
        let critical = false
        if (seen && seen.version !== row.version) {
          const before = await packetVersion(ctx.db, jobId, seen.version)
          critical = before
            ? packetChanges(before.content as PacketContent, row.content).some((c) => c.critical)
            : false
        }
        const ack = await acknowledgmentStatus(ctx.db, row, actor.userId, assigned.includes(jobId))
        packets.push({
          jobId,
          projectReference: row.content.identity.projectReference,
          version: row.version,
          lastViewedVersion: seen?.version ?? null,
          changedSinceViewed: seen !== null && seen.version !== row.version,
          criticalSinceViewed: critical,
          acknowledgment: ack.state,
          acknowledgedVersion: ack.acknowledgment?.version ?? null,
          visits: rows
            .filter((r) => r.job_id === jobId)
            .map((r) => ({
              visitId: r.id,
              number: r.number,
              purpose: r.purpose,
              state: r.state,
              localDate: r.local_date,
              windowStart: r.window_start.slice(0, 5),
              windowEnd: r.window_end.slice(0, 5),
              timeZone: r.time_zone,
              role: r.role ?? 'member',
            })),
        })
      }
      return { body: { packets }, headers: { 'cache-control': 'no-store' } }
    },
  }

  const acknowledgeRoute: RouteDef = {
    ...common,
    method: 'POST',
    path: '/staff/jobs/:jobId/packet/acknowledgments',
    operationId: 'acknowledgeJobPacket',
    summary: "Record the caller's own acknowledgment of the latest packet version",
    description:
      'Staff with job.view_packet who are themselves assigned to the job right now (an active confirmed reservation ' +
      'on a live visit, inside its access window; PROPOSED: the matrix has no acknowledgment row). Records that the ' +
      'caller personally reviewed the given version: it must be the latest one with the exact content digest the ' +
      'caller read (else CONFLICT PACKET_CHANGED: review the new version). Personal: nobody acknowledges for another ' +
      'person and nobody inherits one (CONFLICT NOT_ASSIGNED for anyone not assigned). Acknowledging the standing ' +
      'version again adds nothing (200). Also records the view of that version. A critical change, the end of the ' +
      "caller's assignment or a disabled account later ends it, once. It never releases a hold and is not the Start " +
      'Job gate by itself. Audited.',
    kind: 'write',
    idempotency: 'none',
    expectedVersion: 'none',
    audit: 'job_packet.acknowledge',
    test: ACK_TEST,
    schema: { params: JOB_PARAMS, body: ACKNOWLEDGE_BODY, response: { 200: ACKNOWLEDGED, 201: ACKNOWLEDGED } },
    handler: async (ctx) => {
      const tx = ctx.tx as Tx
      const actor = staff(ctx)
      // Brought up to date under the job's packet lock, held until commit: no version can slip in between.
      const latest = await currentPacket(ctx, tx)
      const { version, contentSha256 } = ctx.req.body as { version: number; contentSha256: string }
      if (version !== latest.version || contentSha256 !== latest.contentSha256)
        throw new ApiError('CONFLICT', {
          fieldErrors: [{ field: 'body.version', code: 'PACKET_CHANGED', message: '' }],
        })
      const now = new Date()
      if (!(await assignedNow(tx, latest.jobId, now)).includes(actor.userId))
        throw new ApiError('CONFLICT', { fieldErrors: [{ field: 'assignment', code: 'NOT_ASSIGNED', message: '' }] })
      const ack = await acknowledge(tx, { row: latest, staffUserId: actor.userId, requestId: requestIdOf(ctx) })
      if (ack.created)
        await tx
          .insertInto('work.job_packet_views')
          .values({ packet_id: latest.id, job_id: latest.jobId, version: latest.version, staff_user_id: actor.userId })
          .execute()
      await ctx.audit({
        target: { type: 'job_packet', id: latest.jobId, version: latest.version },
        summary: { version: latest.version, created: ack.created, scopeVersion: latest.content.scope.version },
      })
      return {
        status: ack.created ? 201 : 200,
        body: {
          acknowledgmentId: ack.id,
          version: ack.version,
          acknowledgedAt: ack.acknowledgedAt,
          created: ack.created,
          state: 'acknowledged',
        },
      }
    },
  }

  return { name: 'packets', routes: [view, versions, recordView, print, pdf, mine, acknowledgeRoute] }
}
