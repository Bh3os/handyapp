// Precompiles the request form's JSON schema (@handyhub/domain/request-form) into a plain validation function with
// Ajv's standalone code (TSK-0017). Ajv normally compiles schemas in the browser with `new Function`, which the
// Content-Security-Policy refuses (no 'unsafe-eval'); the generated module needs no eval at all.
//   pnpm --filter @handyhub/site run validator     (after pnpm build; a unit test checks the committed file is current)
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { Ajv } from 'ajv'
import standaloneCode from 'ajv/dist/standalone/index.js'

// Ajv's runtime helper for maxLength/minLength (counts code points), inlined so the module imports nothing.
const UCS2LENGTH = `function ucs2length(str) {
  const len = str.length
  let length = 0
  let pos = 0
  let value
  while (pos < len) {
    length++
    value = str.charCodeAt(pos++)
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      value = str.charCodeAt(pos)
      if ((value & 0xfc00) === 0xdc00) pos++
    }
  }
  return length
}`

/** The generated module's source for a schema. */
export function validatorSource(schema) {
  const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } })
  const code = standaloneCode(ajv, ajv.compile(schema))
    .replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, 'ucs2length')
    .replace(/^"use strict";/, '')
  if (/require\(|new Function|eval\(/.test(code))
    throw new Error('the generated validator must import and eval nothing')
  return [
    '// @ts-nocheck',
    '/* eslint-disable */',
    '// Generated by apps/site/scripts/request-validator.mjs from REQUEST_FORM_SCHEMA; do not edit.',
    UCS2LENGTH,
    code,
    '',
  ].join('\n')
}

export const OUTPUT = fileURLToPath(new URL('../src/request/validator.generated.ts', import.meta.url))

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { REQUEST_FORM_SCHEMA } = await import('@handyhub/domain/request-form')
  writeFileSync(OUTPUT, validatorSource(REQUEST_FORM_SCHEMA))
  process.stdout.write(`wrote ${OUTPUT}\n`)
}
