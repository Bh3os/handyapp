#!/usr/bin/env node
// Writes docs/service-content-report.md (TSK-0132; OWN-DEC-180 requirement 15, HH-CUS-02, HH-QA-05): the 26
// services, their publishing status, the corrections made, the content and care lines withheld for safety or factual
// verification, the product-dependent care lines and the flags list. Generated from
// packages/domain/src/service-content.ts and packages/db/seed/services.json; never hand-edited.
//
// Usage: node tools/service-content-report.mjs [--check]   (--check exits 1 when the committed report is out of date)
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { SERVICE_CONTENT, SERVICE_CONTENT_REVIEW } from '../packages/domain/src/service-content.ts'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'docs', 'service-content-report.md')
const CATEGORY = {
  home_improvement: 'Home Improvement',
  drywall: 'Drywall',
  painting: 'Painting',
  cleaning: 'Cleaning',
}
const ORDER = ['home_improvement', 'drywall', 'painting', 'cleaning']

const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ')

/** The publishing status of one registry entry. */
export function status(entry, reviewed) {
  if (!reviewed || entry.publicStatus !== 'published') return 'Withheld (draft)'
  const withheld = reviewed.withheldContent.length + reviewed.care.withheld.length
  return withheld ? 'Published, corrected; parts withheld' : 'Published, corrected'
}

export function renderReport(
  registry = JSON.parse(readFileSync(join(ROOT, 'packages/db/seed/services.json'), 'utf8')),
) {
  const services = ORDER.flatMap((c) => registry.services.filter((s) => s.category === c))
  const lines = []
  const push = (...l) => lines.push(...l)
  const totals = { published: 0, withheldContent: 0, withheldCare: 0, product: 0, flags: 0, corrections: 0 }
  for (const s of services) {
    const r = SERVICE_CONTENT[s.id]
    if (r && s.publicStatus === 'published') totals.published++
    totals.withheldContent += r?.withheldContent.length ?? 0
    totals.withheldCare += r?.care.withheld.length ?? 0
    totals.product += r?.care.product.length ?? 0
    totals.flags += r?.flags.length ?? 0
    totals.corrections += r?.corrections.length ?? 0
  }

  push(
    '# Service content report (TSK-0132)',
    '',
    '<!-- Generated by tools/service-content-report.mjs from packages/domain/src/service-content.ts. Do not edit. -->',
    '',
    `Quality review under ${SERVICE_CONTENT_REVIEW.decision} (owner answers 2026-10-21 R8-Q3), built by ${SERVICE_CONTENT_REVIEW.task}, reviewed ${SERVICE_CONTENT_REVIEW.reviewedOn}. This report is requirement 15 of ${SERVICE_CONTENT_REVIEW.decision}: all 26 services, their publishing status, the corrections made and the content withheld for safety or factual verification.`,
    '',
    '## What the review did',
    '',
    '- **Sources only.** Every customer sentence comes from the service node (`SVC-*`: the PROPOSED neutral summary, "Included work", "Excluded work and limits"), its SOP node (`SOP-*`: section 5 customer preparation, section 17 customer communication) and the owner facts (`FACT-SVC-*`, `FACT-SERVICE-AREA`, `FACT-HOURS`, `OWN-DEC-66`, `OWN-DEC-86`). No price, duration, credential, license, insurance, warranty, guarantee, review, capability or measurement was added.',
    '- **Hidden claims.** Every claim the main plan flags as unverified was removed or reworded (the corrections below); SOP steps held for a policy or a qualified review that does not exist yet are not offered on the page (withheld content).',
    '- **Care notes.** General lines, plus product-dependent lines that always say "follow the manufacturer\'s guidance" and state no time, temperature or chemical (OWN-DEC-81). On a completed job they are filled only from the manufacturer guidance stored on the job\'s product records; a line without guidance is omitted and flagged to staff (`jobCareView`, HH-QA-05). Safety-critical lines that need qualified review are withheld and never shown.',
    '- **Production rule.** A quality-reviewed version carries `OWN-DEC-180` as its approval: the registry sync records the approval on the version and publishes it, and production shows only a published version that carries an approval. No per-service owner approval is needed (it replaces that step of OWN-DEC-84 and OWN-DEC-81). Validated content goes to private staging and, through the existing deployment controls, to production when the launch phases of OWN-DEC-191 allow it.',
    '- **Pages.** Every page has the description, included and not-included work, the estimate approach, preparation, the request-form questions, considerations, the limits, the after-the-work care lines (where applicable), 3 to 5 FAQs, related services and the at-a-glance facts with a link to the 11 counties; a search description and FAQ and Service structured data (areaServed: the 11 counties, no address); "Request a Free Estimate" preselects the service. Customer text is English only (OWN-DEC-162).',
    '- **No professional review is claimed.** Nothing here was reviewed by an attorney, a safety professional, an electrician or any other professional; the reviewers named below are the ones the withheld items wait for (OWN-DEC-212).',
    '',
    '## Summary',
    '',
    `- Services: ${services.length}; published after the review: ${totals.published}; withheld as a whole: ${services.length - totals.published}.`,
    `- Corrections: ${totals.corrections}. Page content withheld: ${totals.withheldContent}. Care lines withheld: ${totals.withheldCare}. Product-dependent care lines: ${totals.product}. Flags for the owner or a reviewer: ${totals.flags}.`,
    '',
    '| Code | Service | Page | Status | Corrections | Withheld content | Withheld care lines | Product care lines | Flags |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  )
  for (const s of services) {
    const r = SERVICE_CONTENT[s.id]
    push(
      `| ${s.code} | ${cell(s.name)} | \`/services/${s.slug}\` | ${status(s, r)} | ${r?.corrections.length ?? 0} | ${
        r?.withheldContent.length ?? 0
      } | ${r?.care.withheld.length ?? 0} | ${r?.care.product.length ?? 0} | ${r?.flags.length ?? 0} |`,
    )
  }

  push('', '## Withheld for safety or factual verification', '')
  push('| Code | Withheld | Kind | Why | Reviewer |', '| --- | --- | --- | --- | --- |')
  for (const s of services) {
    const r = SERVICE_CONTENT[s.id]
    for (const w of r?.withheldContent ?? [])
      push(`| ${s.code} | ${cell(w.topic)} | Page content | ${cell(w.reason)} | ${cell(w.reviewer)} |`)
    for (const w of r?.care.withheld ?? [])
      push(`| ${s.code} | ${cell(w.topic)} | Care line | ${cell(w.reason)} | ${cell(w.reviewer)} |`)
  }

  push('', '## Per service', '')
  for (const c of ORDER) {
    push(`### ${CATEGORY[c]}`, '')
    for (const s of services.filter((x) => x.category === c)) {
      const r = SERVICE_CONTENT[s.id]
      push(`#### ${s.code} ${s.name}`, '', `- Status: ${status(s, r)}. Page: \`/services/${s.slug}\`.`)
      if (!r) {
        push('- No reviewed content: the page stays a draft.', '')
        continue
      }
      push(`- Description: ${r.description}`)
      push('- Corrections:', ...r.corrections.map((x) => `  - ${x}`))
      if (r.care.lines.length || r.care.product.length) {
        push('- Care lines published:')
        for (const l of r.care.lines) push(`  - ${l}`)
        for (const p of r.care.product) push(`  - ${p.text} (product-dependent, \`${p.key}\`)`)
      } else push('- Care lines published: none applicable.')
      if (r.withheldContent.length || r.care.withheld.length) {
        push('- Withheld:')
        for (const w of r.withheldContent) push(`  - Page content: ${w.topic}. ${w.reason} Reviewer: ${w.reviewer}.`)
        for (const w of r.care.withheld) push(`  - Care line: ${w.topic}. ${w.reason} Reviewer: ${w.reviewer}.`)
      }
      if (r.flags.length)
        push('- Flags (kept hidden):', ...r.flags.map((f) => `  - ${f.text} Reviewer: ${f.reviewer}.`))
      push('')
    }
  }
  return `${lines.join('\n').replace(/\n+$/, '')}\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = renderReport()
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
    if (current !== text) {
      console.error('docs/service-content-report.md is out of date: run node tools/service-content-report.mjs')
      process.exit(1)
    }
    console.log('service-content-report.md is up to date')
  } else {
    writeFileSync(OUT, text)
    console.log(`wrote ${OUT}`)
  }
}
