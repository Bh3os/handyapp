export type JobCareView = {
  /** The lines the customer sees, in order: general lines, then product lines filled from stored guidance. */
  readonly lines: readonly string[]
  /** Product lines omitted because the job has no stored manufacturer guidance for them ("product guidance missing"). */
  readonly missingGuidance: readonly string[]
}

/**
 * The care notes a customer sees for one completed job (HH-QA-05, OWN-DEC-81, ENT-CareInstruction): the general lines,
 * and each product-dependent line only when the job's product records hold the manufacturer's guidance for it (by
 * line key); a line without guidance is omitted and returned in missingGuidance for staff. Withheld lines never
 * appear. No time, temperature or chemical is added: the guidance text is shown as stored.
 */
export function jobCareView(care: ServiceCare, guidance: Readonly<Record<string, string | undefined>>): JobCareView {
  const lines = [...care.lines]
  const missingGuidance: string[] = []
  for (const p of care.product) {
    const text = guidance[p.key]?.trim()
    if (text) lines.push(`${p.topic}: ${text}`)
    else missingGuidance.push(p.key)
  }
  return { lines, missingGuidance }
}
